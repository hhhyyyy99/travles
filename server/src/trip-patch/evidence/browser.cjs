const assert=require('node:assert/strict')
const {spawn}=require('node:child_process')
const path=require('node:path')
const root=process.env.STASH_ROOT || path.resolve(__dirname,'../../../..')
const screenshotDir=process.env.STASH_SCREENSHOT_DIR || '/tmp'
const {openApp}=require(root+'/tests/helpers/vite-app.cjs')
const before=process.env.STASH_BEFORE==='1'
;(async()=>{
 let logs='', exited=false, app
 const child=spawn(process.execPath,['--import','tsx',path.join(__dirname,'server.mjs')],{cwd:root,env:{...process.env,STASH_ROOT:root,AMAP_KEY:'',AMAP_WEB_KEY:'',AI_API_KEY:''},stdio:['ignore','pipe','pipe']})
 const stopped=new Promise(r=>child.on('exit',code=>{exited=true;r(code)}))
 try{
  const port=await new Promise((resolve,reject)=>{
   const timer=setTimeout(()=>reject(Error('Backend timeout '+logs)),30000)
   child.once('exit',()=>{clearTimeout(timer);reject(Error('Backend exited '+logs))})
   child.stdout.on('data',chunk=>{logs+=chunk;const m=logs.match(/READY (\d+)/);if(m){clearTimeout(timer);resolve(Number(m[1]))}})
   child.stderr.on('data',chunk=>logs+=chunk)
  })
  app=await openApp({serverPort:port,viewport:{width:1440,height:1000},entry:'/?view=workbench&trip=stash-evidence-trip',amapConfig404:true})
  const {page}=app
  const errors=[];page.on('pageerror',e=>errors.push(String(e)))
  const cdp=await page.context().newCDPSession(page);await cdp.send('Network.enable')
  const events=[];cdp.on('Network.eventSourceMessageReceived',x=>{if(x.eventName==='trip.updated')events.push(JSON.parse(x.data))})
  await page.locator('[data-canvas-card="anchor"]').waitFor()
  await page.locator('[data-action="map-stash-toggle"]').click()
  await page.locator('[data-stash-item="legacy-stash"]').waitFor()
  await page.locator('[data-action="route-optimize"]').click()
  if(before){
   await page.locator('[data-ai-proposal-status="error"]').waitFor()
   assert.equal(await page.locator('[data-stash-item]').count(),1)
   const error=await page.locator('[data-ai-proposal-error]').innerText()
   await page.screenshot({path:path.join(screenshotDir,'stash-before.png')})
   console.log(JSON.stringify({baseline:true,error,stashCount:1,errors}))
  }else{
   await page.locator('[data-ai-proposal-confirm]').waitFor()
   const preview=await page.evaluate(async()=>({stash:await (await fetch('/api/trips/stash-evidence-trip/stash')).json(),canvas:await (await fetch('/api/trips/stash-evidence-trip/canvas')).json()}))
   assert.equal(preview.stash.stash.length,1,'preview cannot persist new stash')
   assert.equal(preview.canvas.days.flatMap(d=>d.items).length,1,'preview cannot schedule item')
   await page.locator('[data-ai-proposal-confirm]').click()
   await page.locator('[data-ai-proposal-status="applied"]').waitFor()
   await page.locator('[data-stash-item="dinner-1"]').waitFor()
   assert.equal(await page.locator('[data-stash-item="legacy-stash"]').count(),0)
   await page.locator('[data-canvas-card="scheduled-park"]').waitFor()
   await page.waitForFunction(()=>document.querySelector('[data-stash-item="dinner-1"] [data-action="stash-select"]').textContent==='晚餐灵感')
   const result=await page.evaluate(async()=>{const {fetchRecommendations}=await import('/src/domain/recommendations.ts');const {fetchTripCanvas}=await import('/src/domain/workbench.ts');return {recommendations:await fetchRecommendations('stash-evidence-trip'),canvas:await fetchTripCanvas('stash-evidence-trip')}})
   assert.equal(result.recommendations.ok,true);assert.equal(result.canvas.ok,true)
   assert.equal(result.recommendations.data.stash[0].poi,null)
   assert.equal(result.recommendations.data.stash[0].note,'  到店再选，预算 ¥80/人  ')
   assert.equal(result.recommendations.data.favorites.length,1)
   assert.equal(result.canvas.data.days[0].items[0].timeRange,'09:00')
   assert.equal(result.canvas.data.days[0].items[0].cost,'免费')
   assert.equal(result.canvas.data.legs.length,1)
   assert.ok(result.canvas.data.legs[0].distanceKm>0)
   assert.ok(events.some(e=>e.reason==='ai_proposal'),'native EventSource delivered AI invalidation')
   await page.screenshot({path:path.join(screenshotDir,'stash-after.png')})
   await page.locator('[data-stash-item="dinner-1"] [data-action="stash-schedule"]').click()
   await page.waitForFunction(()=>!document.querySelector('[data-stash-item="dinner-1"]'))
   await page.waitForFunction(()=>Array.from(document.querySelectorAll('[data-canvas-card]')).some(e=>e.textContent.includes('晚餐灵感')))
   const manual=await page.evaluate(async()=>{const {fetchTripCanvas}=await import('/src/domain/workbench.ts');return fetchTripCanvas('stash-evidence-trip')})
   const dinner=manual.data.days[0].items.find(i=>i.title==='晚餐灵感')
   assert.equal(dinner.poi,null);assert.equal(dinner.type,'other');assert.equal(dinner.note,'到店再选，预算 ¥80/人')
   const rawManual=await page.evaluate(async()=>await (await fetch('/api/trips/stash-evidence-trip/canvas')).json())
   assert.equal(rawManual.days[0].items.find(i=>i.title==='晚餐灵感').note,'到店再选，预算 ¥80/人','existing canvas HTTP mapper trims activity notes')
   // Add another real text candidate via the model tool and actual confirmation route, then drag the rendered row.
   await page.locator('[data-action="route-optimize"]').click()
   await page.locator('[data-ai-proposal-confirm]').waitFor()
   await page.locator('[data-ai-proposal-confirm]').click()
   await page.locator('[data-stash-item="dinner-2"]').waitFor()
   await page.locator('[data-stash-item="dinner-2"]').dragTo(page.locator('[data-canvas-day="stash-evidence-day"]'))
   await page.waitForFunction(()=>!document.querySelector('[data-stash-item="dinner-2"]'))
   const dragged=await page.evaluate(async()=>{const {fetchTripCanvas}=await import('/src/domain/workbench.ts');return fetchTripCanvas('stash-evidence-trip')})
   const draggedItem=dragged.data.days[0].items.find(i=>i.title==='晚餐灵感 2')
   assert.ok(draggedItem,'native drag/drop schedules real text candidate');assert.equal(draggedItem.poi,null)
   // Distinct authored candidates can share a POI; row selection must retain the stash identity.
   await page.locator('[data-action="route-optimize"]').click()
   await page.locator('[data-ai-proposal-confirm]').waitFor()
   await page.locator('[data-ai-proposal-confirm]').click()
   await page.locator('[data-stash-item="same-poi-dinner"]').waitFor()
   await page.locator('[data-stash-item="same-poi-supper"] [data-action="stash-select"]').click()
   await page.locator('[data-action="recommendation-add"]').waitFor()
   await page.locator('[data-stash-item="same-poi-supper"] [data-action="stash-remove"]').click()
   await page.waitForFunction(()=>!document.querySelector('[data-stash-item="same-poi-supper"]'))
   assert.equal(await page.locator('[data-action="recommendation-add"]').count(),0,'removed selected candidate must not fall back to another candidate')
   assert.equal(await page.locator('[data-stash-item="same-poi-breakfast"]').count(),1)
   await page.locator('[data-stash-item="same-poi-breakfast"] [data-action="stash-select"]').click()
   await page.locator('[data-action="recommendation-add"]').waitFor()
   await page.locator('[data-stash-item="same-poi-dinner"] [data-action="stash-select"]').click()
   await page.locator('[data-action="recommendation-add"]').click()
   await page.waitForFunction(()=>!document.querySelector('[data-stash-item="same-poi-dinner"]'))
   assert.equal(await page.locator('[data-stash-item="same-poi-breakfast"]').count(),1)
   const selected=await page.evaluate(async()=>{const {fetchTripCanvas}=await import('/src/domain/workbench.ts');return fetchTripCanvas('stash-evidence-trip')})
   assert.ok(selected.data.days[0].items.some(i=>i.title==='晚餐想法'&&i.note==='晚上来'))
   assert.ok(!selected.data.days[0].items.some(i=>i.title==='早餐想法'))
   assert.deepEqual(errors,[])
   console.log(JSON.stringify({baseline:false,previewReadOnly:true,favoritesRetained:1,atomicMove:true,estimatedLeg:true,nativeEvents:events.map(e=>e.reason),manualText:true,dragText:true,samePoiStashIdentity:true,errors}))
  }
 }finally{
  await app?.close()
  if(!exited)child.kill('SIGTERM')
  const code=await stopped
  if(code!==0)throw Error('backend exit '+code+' '+logs)
 }
})().catch(error=>{console.error(error);process.exitCode=1})
