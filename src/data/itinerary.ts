/** [lat, lng] coordinates of the day's points in route order (points[k].xy). */
export function dayPointCoords(dayIndex: number): LatLng[] {
  const day = tripPlan.days[dayIndex]
  if (!day) return []
  return day.points.map((key) => tripPlan.points[key]?.xy ?? [0, 0])
}

